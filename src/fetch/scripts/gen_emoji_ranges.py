"""Generate src/mcp_server_fetch/_emoji_ranges.py from the official Unicode emoji-data.txt.

Usage:
    uv run --locked python scripts/gen_emoji_ranges.py scripts/data/emoji-data.txt [--check]

The output is stable under `ruff format`; --check exits 1 if the committed module differs.
"""

import hashlib
import re
import sys
from pathlib import Path

EXPECTED_SHA256 = "80d00f8e616a0ef27fd6b8de3b758c06383b5d917e2977709578e68baf733bf1"
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "mcp_server_fetch" / "_emoji_ranges.py"
LICENSE = ROOT / "scripts" / "data" / "unicode-license.txt"
PROPERTIES = ("Extended_Pictographic", "Emoji_Modifier")


def merged(ranges: list[tuple[int, int]]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for lo, hi in sorted(ranges):
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out


def table(name: str, ranges: list[tuple[int, int]]) -> str:
    head = f"{name}: tuple[tuple[int, int], ...] = "
    if len(ranges) == 1:  # ruff format joins a one-row tuple onto one line
        lo, hi = ranges[0]
        return f"{head}((0x{lo:04X}, 0x{hi:04X}),)\n"
    rows = "".join(f"    (0x{lo:04X}, 0x{hi:04X}),\n" for lo, hi in ranges)
    return f"{head}(\n{rows})\n"


def fail(message: str) -> None:
    print(message, file=sys.stderr)
    raise SystemExit(2)


def build(path: Path) -> str:
    data = path.read_bytes()
    source = hashlib.sha256(data).hexdigest()
    if source != EXPECTED_SHA256:
        fail("emoji-data.txt does not match the pinned checksum")
    text = data.decode("utf-8")
    version = re.search(r"^# Version: (\d+\.\d+\.\d+)$", text, re.MULTILINE)
    year = re.search(
        r"^# (?:Copyright )?© (?:\d{4}-)?(\d{4}) Unicode", text, re.MULTILINE
    )
    if version is None or year is None:
        fail("emoji-data.txt has no '# Version: X.Y.Z' or copyright line")
    assert version is not None and year is not None
    found: dict[str, list[tuple[int, int]]] = {p: [] for p in PROPERTIES}
    for line in text.splitlines():
        fields = line.split("#", 1)[0].split(";")
        if len(fields) == 2 and fields[1].strip() in found:
            lo, _, hi = fields[0].strip().partition("..")
            found[fields[1].strip()].append((int(lo, 16), int(hi or lo, 16)))
    pictographic = merged(found["Extended_Pictographic"])
    modifier = merged(found["Emoji_Modifier"])
    digest = hashlib.sha256(
        repr((tuple(pictographic), tuple(modifier))).encode()
    ).hexdigest()
    notice = "".join(
        f"# {line}".rstrip() + "\n"
        for line in LICENSE.read_text(encoding="utf-8").splitlines()
    )
    return (
        "# Generated by scripts/gen_emoji_ranges.py from emoji-data.txt\n"
        f"# (Unicode {version[1]}), sha256 {source}. Do not edit.\n"
        "#\n"
        f"# Derived from Unicode data files: Copyright © 1991-{year[1]} Unicode, Inc.\n"
        f"{notice}\n"
        f'UNICODE_EMOJI_VERSION = "{version[1]}"\n'
        f'SOURCE_SHA256 = "{source}"\n\n'
        + table("EXTENDED_PICTOGRAPHIC", pictographic)
        + "\n"
        + table("EMOJI_MODIFIER", modifier)
        + f'\nTABLE_SHA256 = "{digest}"\n'
    )


def main() -> int:
    paths = [a for a in sys.argv[1:] if a != "--check"]
    body = build(Path(paths[0]))
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != body:
            print(
                "regenerate: uv run --locked python scripts/gen_emoji_ranges.py "
                "scripts/data/emoji-data.txt",
                file=sys.stderr,
            )
            return 1
        return 0
    OUT.write_text(body, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
